// Что витрина ждёт от загружаемой картинки — одним списком на всю админку.
//
// Живёт отдельным файлом, потому что одну и ту же подпись показывают три разных
// редактора (поле с одной картинкой, галерея товара, галерея подарка), а
// разъехавшиеся подписи хуже отсутствующих: владелец режет фото под цифру,
// которой на сайте уже нет.
//
// Соотношение — то, по которому витрина режет фото (`object-cover`, по центру).
// Картинка другой формы не растянется — у неё срежет края, поэтому главное
// должно быть в центре кадра.
//
// Размер — сколько пикселей имеет смысл загружать. Сервер сам нарезает каждую
// загруженную картинку на варианты шириной 400 / 800 / 1600 px (WEBP_SIZES в
// server/index.js) и отдаёт витрине подходящий, так что больше 1600 по ширине
// не нужно нигде, а меньше — начнёт мылить на больших экранах. Исключение —
// плашка подарка: она размером с ноготь и крупнее 800 не получит никогда.
export const IMAGE_SPECS = {
  /** Карточка товара, категории, отзыва, «Избранного» — вся витрина в 4:5. */
  card: { ratio: '4:5', size: '1600 × 2000' },
  /** Плашка подарка в углу фото: ей отдаётся вариант шириной 400 px. */
  giftBadge: { ratio: '4:5', size: '800 × 1000' },
  /** Первый экран главной, широкий. */
  hero: { ratio: '16:9', size: '2400 × 1350' },
  /** Он же на телефоне — вертикальный. */
  heroMobile: { ratio: '3:4', size: '1200 × 1600' },
  /** Картинка ссылки в соцсетях и мессенджерах — формат диктуют они, не сайт. */
  social: { ratio: '1.91:1', size: '1200 × 630' },
};

/** «Соотношение 4:5, рекомендуем 1600 × 2000 px» — одной строкой для подписи. */
export function imageSpecText(spec) {
  if (!spec?.ratio || !spec?.size) return '';
  return `Соотношение ${spec.ratio}, рекомендуем ${spec.size} px.`;
}
